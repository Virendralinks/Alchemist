/**
 * Attach lyrics and production to the reference tracks. Done here rather than
 * inline so a song's annotations live in one file, and so a track id that has
 * no content simply stays undissected instead of breaking the discography.
 */
export const artists: ArchiveArtist[] = baseArtists.map((artist) => ({
  ...artist,
  albums: artist.albums.map((album) => ({
    ...album,
    tracks: album.tracks.map((track) => {
      const content = referenceContent[track.id];
      if (!content) return track;
      return { ...track, lyrics: content.lyrics, production: content.production };
    }),
  })),
}));
