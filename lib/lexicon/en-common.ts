// lib/lexicon/en-common.ts
//
// Frequency-ranked common English. The rank column is the whole point of this
// bank: it is read in two unrelated places and both readers only care about the
// ordering, never the absolute value.
//
// First reader is per-token language ID. A token found here at a low rank is
// strong evidence for English, which matters because the highest-frequency
// English words are exactly the ones that collide with romanized Hindi (see
// hi-core.ts: is, us, do, to, kar, hai) and the tie has to be broken by prior
// rather than by spelling.
//
// Second reader is the rhyme index builder. The index has a size budget, so it
// admits words in rank order and stops when the budget is spent. Anything past
// the cut is still available for exact lookup but never for candidate
// generation.
//
// Conventions, held constant across the whole file:
//   - Ranks are unique and contiguous from 1, ordered by corpus frequency.
//     Ordering is close to exact for the first three hundred rows and only
//     approximate after that, which is all either reader needs.
//   - Lowercase, single words, letters only. Contractions are skipped: CMUdict
//     keys them inconsistently and the apostrophe would have to be stripped
//     before lookup anyway.
//   - No pronunciation column. CMUdict supplies it; a row here carries only
//     what CMUdict cannot.
//   - Tags are empty on almost every row. 'slang' is set only where the word is
//     genuinely slang, since the Desi/pop-culture toggle filters on it.
//   - Rows past the top thousand are chosen for this app rather than for
//     general coverage: rap register, the -er/-ter rhyme families that carry
//     most multisyllabic English rhyme, and Delhi NCR working vocabulary.

